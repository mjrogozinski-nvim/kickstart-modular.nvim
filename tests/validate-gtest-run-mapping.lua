-- Run from this repository with:
--   make tests

local api = vim.api
local uv = vim.uv
local temporary_project = vim.fn.tempname()
local original_path = vim.env.PATH

local function write_file(path, lines)
  assert(vim.fn.writefile(lines, path) == 0, 'failed to write ' .. path)
end

local function executable_file(path, lines)
  write_file(path, lines)
  assert(uv.fs_chmod(path, 493), 'failed to make executable: ' .. path)
end

local function find_line(lines, text)
  for index, line in ipairs(lines) do
    if line:find(text, 1, true) then
      return index
    end
  end
  error('line not found: ' .. text)
end

local function mapping(lhs)
  return vim.fn.maparg(lhs, 'n', false, true)
end

local function find_hint(bufnr)
  for _, mark in ipairs(api.nvim_buf_get_extmarks(bufnr, -1, 0, -1, { details = true })) do
    local virtual_text = mark[4].virt_text
    if virtual_text and virtual_text[1] and virtual_text[1][1] == '  ▶ ' then
      return mark
    end
  end
end

local function assert_item(actions, bufnr, line, expected)
  local item = assert(actions.test_at_position(bufnr, line - 1, 0), 'no item found on line ' .. line)
  assert(item.kind == expected.kind, vim.inspect { expected = expected, actual = item })
  assert(item.label == expected.label, vim.inspect { expected = expected, actual = item })
  assert(item.filter == expected.filter, vim.inspect { expected = expected, actual = item })
end

local function main()
  vim.opt.swapfile = false

  assert(vim.fn.mkdir(temporary_project .. '/bin', 'p') == 1)
  assert(vim.fn.mkdir(temporary_project .. '/build', 'p') == 1)

  local source = {
    '#include <gtest/gtest.h>',
    '',
    'TEST(PlainSuite, Works) {',
    '  EXPECT_TRUE(true);',
    '}',
    '',
    'class BaseFixture : public ::testing::Test {',
    ' protected:',
    '  int value = 42;',
    '};',
    '',
    'class DerivedFixture : public BaseFixture {};',
    '',
    'TEST_F(DerivedFixture, UsesFixture) {',
    '  EXPECT_EQ(value, 42);',
    '}',
    '',
    'class ParamFixture : public ::testing::TestWithParam<int> {};',
    '',
    'TEST_P(ParamFixture, IsPositive) {',
    '  EXPECT_GT(GetParam(), 0);',
    '}',
    '',
    'INSTANTIATE_TEST_SUITE_P(Positive, ParamFixture, ::testing::Values(1, 2));',
  }

  local source_path = temporary_project .. '/generated_test.cpp'
  local execution_log = temporary_project .. '/executed-arguments'
  write_file(temporary_project .. '/CMakeLists.txt', { '# Generated by validate-gtest-run-mapping.lua' })
  write_file(source_path, source)
  executable_file(temporary_project .. '/bin/cmake', {
    '#!/bin/sh',
    'exit 0',
  })
  executable_file(temporary_project .. '/build/app', {
    '#!/bin/sh',
    'printf "%s\\n" "$@" > "$GTEST_ACTIONS_TEST_LOG"',
  })

  vim.env.PATH = temporary_project .. '/bin:' .. original_path
  vim.env.GTEST_ACTIONS_TEST_LOG = execution_log
  vim.g.mapleader = ' '

  vim.keymap.set('n', '<leader>cm', function() end, { desc = 'default run sentinel' })
  vim.keymap.set('n', '<leader>dm', function() end, { desc = 'default debug sentinel' })

  vim.cmd.edit(vim.fn.fnameescape(source_path))
  local bufnr = api.nvim_get_current_buf()
  local actions = require 'code.gtest-actions'
  local plain_line = find_line(source, 'TEST(PlainSuite')
  local base_fixture_line = find_line(source, 'class BaseFixture')
  local derived_fixture_line = find_line(source, 'class DerivedFixture')
  local fixture_test_line = find_line(source, 'TEST_F(DerivedFixture')
  local parameter_fixture_line = find_line(source, 'class ParamFixture')
  local parameter_test_line = find_line(source, 'TEST_P(ParamFixture')

  assert(vim.wait(5000, function()
    return actions.test_at_position(bufnr, plain_line - 1, 0) ~= nil
  end, 20), 'Tree-sitter did not discover the generated tests')

  assert_item(actions, bufnr, plain_line, {
    kind = 'test',
    label = 'PlainSuite.Works',
    filter = 'PlainSuite.Works',
  })
  assert_item(actions, bufnr, base_fixture_line, {
    kind = 'fixture',
    label = 'BaseFixture',
    filter = 'BaseFixture.*:*/BaseFixture.*/*',
  })
  assert_item(actions, bufnr, derived_fixture_line, {
    kind = 'fixture',
    label = 'DerivedFixture',
    filter = 'DerivedFixture.*:*/DerivedFixture.*/*',
  })
  assert_item(actions, bufnr, fixture_test_line, {
    kind = 'test',
    label = 'DerivedFixture.UsesFixture',
    filter = 'DerivedFixture.UsesFixture',
  })
  assert_item(actions, bufnr, parameter_fixture_line, {
    kind = 'fixture',
    label = 'ParamFixture',
    filter = 'ParamFixture.*:*/ParamFixture.*/*',
  })
  assert_item(actions, bufnr, parameter_test_line, {
    kind = 'test',
    label = 'ParamFixture.IsPositive',
    filter = 'ParamFixture.IsPositive:*/ParamFixture.IsPositive/*',
  })

  api.nvim_win_set_cursor(0, { plain_line, 0 })
  actions.update_hint(bufnr)

  local hint = assert(find_hint(bufnr), 'action hint was not rendered')
  assert(hint[2] == plain_line - 1, vim.inspect(hint))
  assert(hint[4].virt_text[3][1] == '<leader>cm', vim.inspect(hint))
  assert(hint[4].virt_text[6][1] == '<leader>dm', vim.inspect(hint))
  assert(mapping('<leader>cm').desc == 'build and run GoogleTest on this line')
  assert(mapping('<leader>dm').desc == 'build and debug GoogleTest on this line')

  api.nvim_win_set_cursor(0, { plain_line + 1, 0 })
  actions.update_hint(bufnr)
  assert(find_hint(bufnr) == nil, 'hint remained visible outside the declaration line')
  assert(mapping('<leader>cm').desc == 'default run sentinel')
  assert(mapping('<leader>dm').desc == 'default debug sentinel')

  api.nvim_win_set_cursor(0, { plain_line, 0 })
  actions.update_hint(bufnr)

  local overseer = require 'overseer'
  local existing_tasks = {}
  for _, task in ipairs(overseer.list_tasks {}) do
    existing_tasks[task.id] = true
  end

  local run_mapping = mapping('<leader>cm')
  assert(type(run_mapping.callback) == 'function')
  run_mapping.callback()

  local parent
  assert(vim.wait(15000, function()
    for _, task in ipairs(overseer.list_tasks {}) do
      if not existing_tasks[task.id] and task.name == 'run PlainSuite.Works' then
        parent = task
        return task:is_complete()
      end
    end
    return false
  end, 20), 'orchestrated run did not complete')

  assert(parent.status == 'SUCCESS', parent.status)
  local children = {}
  for _, task in ipairs(overseer.list_tasks { include_ephemeral = true }) do
    if task.parent_id == parent.id then
      children[task.name] = task.status
    end
  end
  assert(children.configure == 'SUCCESS', vim.inspect(children))
  assert(children.build == 'SUCCESS', vim.inspect(children))
  assert(children['execute PlainSuite.Works'] == 'SUCCESS', vim.inspect(children))
  assert(vim.deep_equal(vim.fn.readfile(execution_log), { '--gtest_filter=PlainSuite.Works' }))

  api.nvim_set_current_buf(bufnr)
  api.nvim_win_set_cursor(0, { parameter_test_line, 0 })
  actions.update_hint(bufnr)

  local dap = require 'dap'
  local debug_configuration
  dap.adapters.codelldb = dap.adapters.codelldb or {}
  dap.run = function(configuration)
    debug_configuration = configuration
  end

  local debug_mapping = mapping('<leader>dm')
  assert(type(debug_mapping.callback) == 'function')
  debug_mapping.callback()
  assert(vim.wait(15000, function()
    return debug_configuration ~= nil
  end, 20), 'debug action was not dispatched')

  assert(
    debug_configuration.program == uv.fs_realpath(temporary_project .. '/build/app'),
    vim.inspect {
      expected = uv.fs_realpath(temporary_project .. '/build/app'),
      actual = debug_configuration.program,
    }
  )
  assert(vim.deep_equal(debug_configuration.args, {
    '--gtest_filter=ParamFixture.IsPositive:*/ParamFixture.IsPositive/*',
  }))
end

local ok, error_message = xpcall(main, debug.traceback)
vim.env.PATH = original_path
vim.env.GTEST_ACTIONS_TEST_LOG = nil
vim.fn.delete(temporary_project, 'rf')

if not ok then
  io.stderr:write(error_message .. '\n')
  vim.cmd 'cquit 1'
else
  print 'GoogleTest actions: all checks passed'
  vim.cmd 'qall!'
end
